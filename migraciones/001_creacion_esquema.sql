-- =============================================================================
-- MIGRACIÓN 001: CREACIÓN DE ESQUEMA INTEGRAL GYMBROT
-- Motor: PostgreSQL 12+
-- Descripción: Creación de tablas, claves primarias, foráneas, restricciones de
--              integridad (CHECK, UNIQUE), índices y políticas de borrado.
--              Incluye la tabla GIMNASIOS (multitenant): cada usuario y cada
--              catálogo propio pertenece a un gimnasio.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 0. MULTITENANT
-- -----------------------------------------------------------------------------

-- 0.1 GIMNASIOS (Tenant)
CREATE TABLE gimnasios (
    id_gimnasio       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slug              VARCHAR(40) NOT NULL,
    nombre            VARCHAR(100) NOT NULL,
    ciudad            VARCHAR(60) NULL,
    telefono          VARCHAR(20) NULL,
    plan_software     VARCHAR(20) NOT NULL,
    estado            VARCHAR(20) NOT NULL,
    fecha_registro    DATE NOT NULL,
    vence_suscripcion DATE NULL,

    CONSTRAINT pk_gimnasios PRIMARY KEY (id_gimnasio),
    CONSTRAINT uq_gimnasios_slug UNIQUE (slug),
    CONSTRAINT chk_gimnasios_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT chk_gimnasios_plan CHECK (plan_software IN ('BASICO', 'PRO', 'PREMIUM')),
    CONSTRAINT chk_gimnasios_estado CHECK (estado IN ('ACTIVO', 'SUSPENDIDO', 'INACTIVO')),
    CONSTRAINT chk_gimnasios_fechas CHECK (vence_suscripcion IS NULL OR vence_suscripcion >= fecha_registro)
);

-- -----------------------------------------------------------------------------
-- 1. TABLAS DE CATÁLOGOS Y USUARIOS
-- -----------------------------------------------------------------------------

-- 1.1 USUARIOS (Entidad Base)
-- El SUPERADMIN administra la plataforma y es el único sin gimnasio.
CREATE TABLE usuarios (
    numero_identificacion VARCHAR(20) NOT NULL,
    id_gimnasio           BIGINT NULL,
    tipo_identificacion   VARCHAR(10) NOT NULL,
    nombre                VARCHAR(200) NOT NULL,
    apellidos             VARCHAR(200) NOT NULL,
    telefono              VARCHAR(20) NULL,
    correo                VARCHAR(150) NULL,
    contrasena_hash       VARCHAR(255) NULL,
    foto_url              VARCHAR(500) NULL,
    estado                VARCHAR(20) NOT NULL,
    fecha_registro        DATE NOT NULL,
    tipo_usuario          VARCHAR(20) NOT NULL,

    CONSTRAINT pk_usuarios PRIMARY KEY (numero_identificacion),
    CONSTRAINT fk_usuarios_gimnasio
        FOREIGN KEY (id_gimnasio)
        REFERENCES gimnasios(id_gimnasio)
        ON DELETE RESTRICT,
    CONSTRAINT chk_usuarios_tipo_id CHECK (tipo_identificacion IN ('CC', 'TI', 'CE', 'PP')),
    CONSTRAINT chk_usuarios_tipo_usuario CHECK (tipo_usuario IN ('CLIENTE', 'INSTRUCTOR', 'ADMINISTRADOR', 'SUPERADMIN')),
    CONSTRAINT chk_usuarios_estado CHECK (estado IN ('ACTIVO', 'INACTIVO', 'SUSPENDIDO', 'BLOQUEADO')),
    CONSTRAINT chk_usuarios_gimnasio CHECK ((tipo_usuario = 'SUPERADMIN') = (id_gimnasio IS NULL)),
    CONSTRAINT uq_usuarios_correo UNIQUE (correo)
);

-- 1.2 ESPECIALIDADES (Requerida previamente por INSTRUCTORES)
CREATE TABLE especialidades (
    id_especialidad BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(100) NOT NULL,

    CONSTRAINT pk_especialidades PRIMARY KEY (id_especialidad),
    CONSTRAINT uq_especialidades_nombre UNIQUE (nombre)
);

-- 1.3 CLIENTES (Subtipo de USUARIOS)
CREATE TABLE clientes (
    numero_identificacion VARCHAR(20) NOT NULL,
    direccion             VARCHAR(300) NULL,
    fecha_nacimiento      DATE NULL,
    huella_dactilar       BYTEA NULL,

    CONSTRAINT pk_clientes PRIMARY KEY (numero_identificacion),
    CONSTRAINT fk_clientes_usuarios
        FOREIGN KEY (numero_identificacion)
        REFERENCES usuarios(numero_identificacion)
        ON DELETE RESTRICT
);

-- 1.4 INSTRUCTORES (Subtipo de USUARIOS)
CREATE TABLE instructores (
    numero_identificacion VARCHAR(20) NOT NULL,
    id_especialidad       BIGINT NOT NULL,
    disponibilidad        VARCHAR(200) NULL,
    fecha_contratacion    DATE NULL,

    CONSTRAINT pk_instructores PRIMARY KEY (numero_identificacion),
    CONSTRAINT fk_instructores_usuarios
        FOREIGN KEY (numero_identificacion)
        REFERENCES usuarios(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT fk_instructores_especialidad
        FOREIGN KEY (id_especialidad)
        REFERENCES especialidades(id_especialidad)
        ON DELETE RESTRICT
);

-- 1.5 ADMINISTRADORES (Subtipo de USUARIOS)
CREATE TABLE administradores (
    numero_identificacion VARCHAR(20) NOT NULL,
    rol                   VARCHAR(30) NOT NULL,

    CONSTRAINT pk_administradores PRIMARY KEY (numero_identificacion),
    CONSTRAINT fk_administradores_usuarios
        FOREIGN KEY (numero_identificacion)
        REFERENCES usuarios(numero_identificacion)
        ON DELETE CASCADE
);

-- 1.6 PLANES_MEMBRESIAS (Cada gimnasio define sus propios planes)
CREATE TABLE planes_membresias (
    id_plan          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_gimnasio      BIGINT NOT NULL,
    nombre           VARCHAR(100) NOT NULL,
    descripcion      VARCHAR(500) NULL,
    precio_mensual   NUMERIC(10, 2) NULL,
    precio_semestral NUMERIC(10, 2) NULL,
    precio_anual     NUMERIC(10, 2) NULL,
    beneficios       TEXT NULL,

    CONSTRAINT pk_planes_membresias PRIMARY KEY (id_plan),
    CONSTRAINT fk_planes_gimnasio
        FOREIGN KEY (id_gimnasio)
        REFERENCES gimnasios(id_gimnasio)
        ON DELETE RESTRICT,
    CONSTRAINT uq_planes_gimnasio_nombre UNIQUE (id_gimnasio, nombre),
    CONSTRAINT chk_planes_precio_mensual CHECK (precio_mensual >= 0),
    CONSTRAINT chk_planes_precio_semestral CHECK (precio_semestral >= 0),
    CONSTRAINT chk_planes_precio_anual CHECK (precio_anual >= 0)
);

-- 1.7 EJERCICIOS (id_gimnasio NULL = catálogo base compartido por todos los gimnasios)
CREATE TABLE ejercicios (
    id_ejercicio     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_gimnasio      BIGINT NULL,
    nombre           VARCHAR(150) NOT NULL,
    descripcion      TEXT NULL,
    grupo_muscular   VARCHAR(100) NULL,
    series           SMALLINT NULL,
    repeticiones     SMALLINT NULL,
    duracion_minutos SMALLINT NULL,
    nivel            VARCHAR(20) NULL,
    recurso_url      VARCHAR(500) NULL,

    CONSTRAINT pk_ejercicios PRIMARY KEY (id_ejercicio),
    CONSTRAINT fk_ejercicios_gimnasio
        FOREIGN KEY (id_gimnasio)
        REFERENCES gimnasios(id_gimnasio)
        ON DELETE RESTRICT,
    CONSTRAINT chk_ejercicios_nivel CHECK (nivel IN ('PRINCIPIANTE', 'INTERMEDIO', 'AVANZADO'))
);

-- 1.8 PLANTILLAS_MENSAJE (id_gimnasio NULL = plantilla del sistema)
CREATE TABLE plantillas_mensaje (
    id_plantilla          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_gimnasio           BIGINT NULL,
    nombre                VARCHAR(100) NOT NULL,
    tipo                  VARCHAR(20) NOT NULL,
    asunto                VARCHAR(200) NULL,
    cuerpo_html           TEXT NULL,
    cuerpo_texto          TEXT NULL,
    variables_disponibles VARCHAR(500) NULL,
    activa                BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_plantillas_mensaje PRIMARY KEY (id_plantilla),
    CONSTRAINT fk_plantillas_gimnasio
        FOREIGN KEY (id_gimnasio)
        REFERENCES gimnasios(id_gimnasio)
        ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- 2. TABLAS TRANSACCIONALES Y OPERATIVAS
-- -----------------------------------------------------------------------------

-- 2.1 MEMBRESIAS
CREATE TABLE membresias (
    id_membresia      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan           BIGINT NOT NULL,
    tipo_membresia    VARCHAR(50) NULL,
    modalidad_pago    VARCHAR(20) NULL,
    valor             NUMERIC(10, 2) NULL,
    fecha_inicio      DATE NULL,
    fecha_vencimiento DATE NULL,
    estado            VARCHAR(20) NOT NULL,

    CONSTRAINT pk_membresias PRIMARY KEY (id_membresia),
    CONSTRAINT fk_membresias_plan
        FOREIGN KEY (id_plan)
        REFERENCES planes_membresias(id_plan)
        ON DELETE RESTRICT,
    CONSTRAINT chk_membresias_valor CHECK (valor >= 0),
    CONSTRAINT chk_membresias_fechas CHECK (fecha_vencimiento >= fecha_inicio)
);

-- 2.2 HISTORIAL_MEMBRESIAS (Asociativa CLIENTES - MEMBRESIAS)
CREATE TABLE historial_membresias (
    id_historial     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente       VARCHAR(20) NOT NULL,
    id_membresia     BIGINT NOT NULL,
    fecha_asignacion DATE NOT NULL,
    fecha_fin        DATE NULL,
    activa           BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_historial_membresias PRIMARY KEY (id_historial),
    CONSTRAINT fk_historial_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT fk_historial_membresia
        FOREIGN KEY (id_membresia)
        REFERENCES membresias(id_membresia)
        ON DELETE RESTRICT,
    -- Requerida por PAGOS: el pago solo puede ser de una membresía asignada a ese cliente
    CONSTRAINT uq_historial_cliente_membresia UNIQUE (id_cliente, id_membresia),
    CONSTRAINT chk_historial_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_asignacion)
);

-- 2.3 PAGOS
CREATE TABLE pagos (
    id_pago                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_membresia           BIGINT NOT NULL,
    id_cliente             VARCHAR(20) NOT NULL,
    fecha_pago             DATE NOT NULL,
    valor                  NUMERIC(10, 2) NOT NULL,
    metodo_pago            VARCHAR(30) NOT NULL,
    estado_pago            VARCHAR(20) NOT NULL,
    referencia_transaccion VARCHAR(100) NULL,
    observaciones          VARCHAR(500) NULL,

    CONSTRAINT pk_pagos PRIMARY KEY (id_pago),
    CONSTRAINT fk_pagos_membresia
        FOREIGN KEY (id_membresia)
        REFERENCES membresias(id_membresia)
        ON DELETE RESTRICT,
    CONSTRAINT fk_pagos_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT fk_pagos_historial
        FOREIGN KEY (id_cliente, id_membresia)
        REFERENCES historial_membresias(id_cliente, id_membresia)
        ON DELETE RESTRICT,
    CONSTRAINT chk_pagos_valor CHECK (valor > 0),
    CONSTRAINT chk_pagos_estado CHECK (estado_pago IN ('EXITOSO', 'RECHAZADO', 'PENDIENTE'))
);

-- 2.4 RUTINAS
CREATE TABLE rutinas (
    id_rutina      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_instructor  VARCHAR(20) NOT NULL,
    id_cliente     VARCHAR(20) NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    descripcion    TEXT NULL,
    fecha_creacion DATE NOT NULL,
    fecha_fin      DATE NULL,
    dias_semana    VARCHAR(100) NULL,
    objetivo       VARCHAR(200) NULL,

    CONSTRAINT pk_rutinas PRIMARY KEY (id_rutina),
    CONSTRAINT fk_rutinas_instructor
        FOREIGN KEY (id_instructor)
        REFERENCES instructores(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT fk_rutinas_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT chk_rutinas_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_creacion)
);

-- 2.5 RUTINA_EJERCICIOS (Intersección M:N)
-- Clave propia: un mismo ejercicio puede repetirse en la rutina en días distintos.
CREATE TABLE rutina_ejercicios (
    id_rutina_ejercicio BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_rutina           BIGINT NOT NULL,
    id_ejercicio        BIGINT NOT NULL,
    orden               SMALLINT NOT NULL,
    dia_semana          VARCHAR(15) NULL,
    notas_instructor    TEXT NULL,

    CONSTRAINT pk_rutina_ejercicios PRIMARY KEY (id_rutina_ejercicio),
    CONSTRAINT fk_rutina_ejercicios_rutina
        FOREIGN KEY (id_rutina)
        REFERENCES rutinas(id_rutina)
        ON DELETE CASCADE,
    CONSTRAINT fk_rutina_ejercicios_ejercicio
        FOREIGN KEY (id_ejercicio)
        REFERENCES ejercicios(id_ejercicio)
        ON DELETE RESTRICT,
    CONSTRAINT uq_rutina_ejercicios UNIQUE (id_rutina, id_ejercicio, dia_semana),
    CONSTRAINT chk_rutina_ejercicios_orden CHECK (orden > 0),
    CONSTRAINT chk_rutina_ejercicios_dia CHECK (dia_semana IN ('LUNES', 'MARTES', 'MIERCOLES', 'JUEVES', 'VIERNES', 'SABADO', 'DOMINGO'))
);

-- 2.6 PROGRESOS
CREATE TABLE progresos (
    id_progreso      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente       VARCHAR(20) NOT NULL,
    fecha_registro   DATE NOT NULL,
    peso             NUMERIC(6, 2) NULL,
    altura           NUMERIC(5, 2) NULL,
    imc              NUMERIC(5, 2) NULL,
    porcentaje_grasa NUMERIC(5, 2) NULL,
    masa_muscular    NUMERIC(6, 2) NULL,
    objetivo         VARCHAR(200) NULL,
    observaciones    TEXT NULL,

    CONSTRAINT pk_progresos PRIMARY KEY (id_progreso),
    CONSTRAINT fk_progresos_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT chk_progresos_peso CHECK (peso IS NULL OR peso > 0),
    CONSTRAINT chk_progresos_altura CHECK (altura IS NULL OR altura > 0)
);

-- 2.7 REGISTROS_INGRESOS
CREATE TABLE registros_ingresos (
    id_ingreso          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente          VARCHAR(20) NOT NULL,
    fecha               DATE NOT NULL,
    hora_entrada        TIME NULL,
    hora_salida         TIME NULL,
    metodo_verificacion VARCHAR(20) NOT NULL,
    estado_verificacion VARCHAR(20) NOT NULL,

    CONSTRAINT pk_registros_ingresos PRIMARY KEY (id_ingreso),
    CONSTRAINT fk_registros_ingresos_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT chk_ingresos_metodo CHECK (metodo_verificacion IN ('HUELLAS', 'QR', 'MANUAL')),
    CONSTRAINT chk_ingresos_estado CHECK (estado_verificacion IN ('APROBADO', 'RECHAZADO')),
    CONSTRAINT chk_ingresos_horas CHECK (hora_salida IS NULL OR hora_entrada IS NULL OR hora_salida >= hora_entrada)
);

-- 2.8 CITAS
CREATE TABLE citas (
    id_cita       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_instructor VARCHAR(20) NOT NULL,
    id_cliente    VARCHAR(20) NOT NULL,
    fecha         DATE NOT NULL,
    hora          TIME NULL,
    tipo_cita     VARCHAR(30) NULL,
    estado        VARCHAR(20) NOT NULL,
    notas         TEXT NULL,

    CONSTRAINT pk_citas PRIMARY KEY (id_cita),
    CONSTRAINT fk_citas_instructor
        FOREIGN KEY (id_instructor)
        REFERENCES instructores(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT fk_citas_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT chk_citas_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA'))
);

-- 2.9 SESIONES_GYMBROT
CREATE TABLE sesiones_gymbrot (
    id_sesion       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente      VARCHAR(20) NOT NULL,
    fecha           DATE NOT NULL,
    hora_inicio     TIME NULL,
    hora_fin        TIME NULL,
    contexto_activo TEXT NULL,

    CONSTRAINT pk_sesiones_gymbrot PRIMARY KEY (id_sesion),
    CONSTRAINT fk_sesiones_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT chk_sesiones_horas CHECK (hora_fin IS NULL OR hora_inicio IS NULL OR hora_fin >= hora_inicio)
);

-- 2.10 MENSAJES_GYMBROT
CREATE TABLE mensajes_gymbrot (
    id_mensaje     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_sesion      BIGINT NOT NULL,
    id_cita        BIGINT NULL,
    remitente      VARCHAR(10) NOT NULL,
    contenido      TEXT NOT NULL,
    timestamp_msg  TIMESTAMP NOT NULL,
    tipo_intencion VARCHAR(30) NULL,

    CONSTRAINT pk_mensajes_gymbrot PRIMARY KEY (id_mensaje),
    CONSTRAINT fk_mensajes_sesion
        FOREIGN KEY (id_sesion)
        REFERENCES sesiones_gymbrot(id_sesion)
        ON DELETE CASCADE,
    CONSTRAINT fk_mensajes_cita
        FOREIGN KEY (id_cita)
        REFERENCES citas(id_cita)
        ON DELETE SET NULL,
    CONSTRAINT chk_mensajes_remitente CHECK (remitente IN ('CLIENTE', 'GYMBROT'))
);

-- 2.11 NOTIFICACIONES
CREATE TABLE notificaciones (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente      VARCHAR(20) NOT NULL,
    id_plantilla    BIGINT NULL,
    tipo            VARCHAR(20) NOT NULL,
    asunto          VARCHAR(200) NULL,
    contenido       TEXT NOT NULL,
    estado_envio    VARCHAR(20) NOT NULL,
    fecha_envio     TIMESTAMP NULL,
    origen          VARCHAR(20) NOT NULL,

    CONSTRAINT pk_notificaciones PRIMARY KEY (id_notificacion),
    CONSTRAINT fk_notificaciones_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(numero_identificacion)
        ON DELETE RESTRICT,
    CONSTRAINT fk_notificaciones_plantilla
        FOREIGN KEY (id_plantilla)
        REFERENCES plantillas_mensaje(id_plantilla)
        ON DELETE SET NULL,
    CONSTRAINT chk_notificaciones_tipo CHECK (tipo IN ('EMAIL', 'SMS', 'OTRO')),
    CONSTRAINT chk_notificaciones_estado CHECK (estado_envio IN ('PENDIENTE', 'ENVIADO', 'FALLIDO')),
    CONSTRAINT chk_notificaciones_origen CHECK (origen IN ('SISTEMA', 'BOT', 'MANUAL'))
);

-- -----------------------------------------------------------------------------
-- 3. ÍNDICES SOBRE CLAVES FORÁNEAS
-- PostgreSQL no indexa las FK automáticamente. Se omiten las columnas que ya
-- encabezan una PK o un UNIQUE (ej. historial_membresias.id_cliente).
-- -----------------------------------------------------------------------------

CREATE INDEX ix_usuarios_gimnasio           ON usuarios (id_gimnasio);
CREATE INDEX ix_instructores_especialidad   ON instructores (id_especialidad);
CREATE INDEX ix_ejercicios_gimnasio         ON ejercicios (id_gimnasio);
CREATE INDEX ix_plantillas_gimnasio         ON plantillas_mensaje (id_gimnasio);
CREATE INDEX ix_membresias_plan             ON membresias (id_plan);
CREATE INDEX ix_historial_membresia         ON historial_membresias (id_membresia);
CREATE INDEX ix_pagos_cliente_membresia     ON pagos (id_cliente, id_membresia);
CREATE INDEX ix_pagos_membresia             ON pagos (id_membresia);
CREATE INDEX ix_rutinas_instructor          ON rutinas (id_instructor);
CREATE INDEX ix_rutinas_cliente             ON rutinas (id_cliente);
CREATE INDEX ix_rutina_ejercicios_ejercicio ON rutina_ejercicios (id_ejercicio);
CREATE INDEX ix_progresos_cliente           ON progresos (id_cliente, fecha_registro);
CREATE INDEX ix_ingresos_cliente            ON registros_ingresos (id_cliente, fecha);
CREATE INDEX ix_citas_instructor            ON citas (id_instructor, fecha);
CREATE INDEX ix_citas_cliente               ON citas (id_cliente, fecha);
CREATE INDEX ix_sesiones_cliente            ON sesiones_gymbrot (id_cliente);
CREATE INDEX ix_mensajes_sesion             ON mensajes_gymbrot (id_sesion);
CREATE INDEX ix_mensajes_cita               ON mensajes_gymbrot (id_cita);
CREATE INDEX ix_notificaciones_cliente      ON notificaciones (id_cliente);
CREATE INDEX ix_notificaciones_plantilla    ON notificaciones (id_plantilla);

COMMIT;
